def _next_weekday(d):
    d += timedelta(days=1)
    while d.weekday() >= 5:
        d += timedelta(days=1)
    return d


def _build_event_index():
    """One dict: date -> [tags]."""
    index = {}

    def add(date_str, tag):
        tags = index.setdefault(date_str, [])
        if tag not in tags:
            tags.append(tag)

    for tag, dates in (("FOMC", FOMC_DATES), ("CPI", CPI_DATES), ("PPI", PPI_DATES), ("JOBS", JOBS_DATES),
                       ("PCE", PCE_DATES), ("GDP", GDP_DATES)):
        for d in dates:
            add(d, tag)
    # Reports come out after the close, so tag the next trading morning.
    for ticker, dates in EARNINGS_REPORTS.items():
        for d in dates:
            add(_next_weekday(date.fromisoformat(d)).isoformat(), f"earnings:{ticker}")
    return index


EVENT_DATES = _build_event_index()   # built once at import


def get_events_today(date_str):
    """Tags for date_str ('YYYY-MM-DD'), e.g. ['CPI'] or ['earnings:NVDA']. Empty list if none."""
    return list(EVENT_DATES.get(date_str, []))


def is_fomc(date_str):
    """True if date_str ('YYYY-MM-DD') is an FOMC decision day."""
    return "FOMC" in EVENT_DATES.get(date_str, [])
